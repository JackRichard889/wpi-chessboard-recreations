<h2 class="mb-3 text-xl font-bold">DeMoivre's Knight Tour</h2>
<p class="mb-1">
	Abraham de Moivre (1667–1754) was a French mathematician who fled to England after the revocation
	of the Edict of Nantes. Best known for de Moivre's theorem in complex analysis and his
	foundational work in probability theory, he also carried out a systematic study of the
	knight's tour problem.
</p>
<p class="mb-1">
	His tour on the 8×8 board is an open tour in which the knight visits every square exactly once but cannot
	return to its starting square at the end in a single move. It begins from a corner of the board and
	weaves over all 64 squares before ending up close to another corner of the board.
</p>
