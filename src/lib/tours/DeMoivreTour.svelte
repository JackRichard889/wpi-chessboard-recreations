<h2 class="mb-3 text-xl font-bold">DeMoivre's Knight Tour</h2>
<p class="mb-1">
	Abraham de Moivre (1667–1754) was a French mathematician who fled to England after the revocation
	of the Edict of Nantes. Best known for de Moivre's theorem in complex analysis and his
	foundational work in probability theory, he was also among the first to systematically study the
	knight's tour problem.
</p>
<p class="mb-1">
	His tour on the 8×8 board is an open tour, the knight visits every square exactly once but cannot
	return to its starting square in a single knight's move. It begins from a corner of the board,
	weaving across all 64 squares before ending on the opposite side.
</p>
