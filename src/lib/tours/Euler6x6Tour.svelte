<h2 class="mb-3 text-xl font-bold">Euler's Knight Tour (6x6)</h2>
<p class="mb-1">
	Leonhard Euler's investigation of knight's tours extended beyond the standard 8×8 chessboard. This
	tour on a 6×6 board demonstrates that a complete knight's tour is possible on smaller boards as
	well.
</p>
<p class="mb-1">
	Unlike many smaller-board tours, this is a closed (re-entrant) tour because the knight can jump back from its
	final square to its starting point, forming a continuous cycle
	across all 36 squares.
</p>
