<h2 class="mb-3 text-xl font-bold">Euler's Knight Tour</h2>
<p class="mb-1">
	The Swiss mathematician Leonhard Euler worked out this way of making a knight jump from square to
	square on a chessboard so that it visits every square just once before returning to its starting
	point. The kight can also jump from the last square of the tour back to ist starting point, so this is knowns as a ''reentrant'' tour.
</p>
<p class="mb-1">
	This tour has another remarkable property. If the squares are numbered in the order that the
	knight visits them, the sum of the numbers in every row and every column of the square is 260.
</p>
