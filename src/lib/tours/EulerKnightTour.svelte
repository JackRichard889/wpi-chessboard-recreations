<h2 class="mb-3 text-xl font-bold">Euler's Knight Tour</h2>
<p class="mb-1">
	The Swiss mathematician Leonhard Euler worked out this way of making a knight jump from square to
	square on a chessboard so that it visits every square exactly once. This kind of tour, in which every one 
    of a number of connected points is visited just once by jumping along the lines joining them, is known as a 
    Hamiltonian path after the Irish mathematician William Rowan Hamilton. Because the knight is able to jump
    back from the final square it visits to its starting point, this type of tour is known as a "Hamiltonian circuit" or
    ''reentrant tour''.
</p>
<p class="mb-1">
	This tour has another remarkable property. If the squares are numbered in the order they are
	visited, the sum of the numbers in every row and column of the chessboard is the same
    and equal to 260. A set of numbers with this property is known as a "magic square" (although the 
    term is sometimes used only for squares for which the sums along the two diagonals also equal the sums 
    along the rows and the columns).
<p class="mb-1">
    The Hindu mathematician Nilakantha came up with solutions to the knight's tour problem 
 a little over half a century before Euler, but Euler's work sparked much of the later work on the problem.    
</p>
