<h2 class="mb-3 text-xl font-bold">King's Magic Tour</h2>
<p class="mb-1">
	A king's tour is a path in which a king, moving one square in any direction, including diagonally,
	visits every square of the board exactly once. Unlike the knight, the king has up to eight
	possible moves from any interior square, making the tour easier to construct but harder to make
	remarkable.
</p>
<p class="mb-1">
	This particular king's tour is both a Hamiltonian circuit and a "magic" tour: if the squares are numbered in the 
    order they are visited, every row and column sums to 260, the same magic constant as for Euler's 8×8
	knight's tour, and the expected value for any magic square of order 8.
</p>
