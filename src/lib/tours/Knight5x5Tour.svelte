<h2 class="mb-3 text-xl font-bold">Knight Tour (5x5)</h2>
<p class="mb-1">
	The 5×5 board presents a fundamental constraint for knight's tours. Because the board has an odd
	number of squares (25) and a knight always alternates between light and dark squares, any complete
	tour must begin on one color and end on the other. This coloring argument proves that a closed
	(re-entrant) tour is impossible on any board with an odd number of squares.
</p>
<p class="mb-1">
	This is therefore an open tour: the knight visits all 25 squares exactly once but cannot return
	to its starting square. Despite the small board size, there are thousands of distinct open
	knight's tours on the 5×5 board.
</p>
