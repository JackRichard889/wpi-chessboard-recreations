<h2 class="mb-3 text-xl font-bold">Knight Tour (7x7)</h2>
<p class="mb-1">
	The 7×7 board has an odd number of squares (49), so no closed (or rentrant) knight's tour is
    possible on it because the knight jumps to a square of the opposite color at every step and cannot return to  
    its original square in an odd number of steps. 
    This is an open tour that visits all 49 squares exactly once. However, to accomplish it, the knight must 
    sometimes jump off an edge of the board and back on to an unvisited square before going on with its tour.   
    In this case, the square it lands back on is the one of the empty ones available to it if the opposite edges of 
    the board glued together, so that it became a torus. 
</p>
<p class="mb-1">
	This knight's tour is also a magic tour. If the squares are numbered in the order they are
	visited, the sum of the numbers in any row or column of the board is 175, the magic constant for a 7×7
	square, since the numbers 1 through 49 sum to 1225, which is 175 x 7.
</p>
