<h2 class="mb-3 text-xl font-bold">Knight Tour (7x7)</h2>
<p class="mb-1">
	Like the 5×5 board, the 7×7 board has an odd number of squares (49), so no closed knight's tour
	exists. This is an open tour that visits all 49 squares exactly once.
</p>
<p class="mb-1">
	This knight's tour is also a magic tour. If the squares are numbered in the order the knight
	visits them, the sum of the numbers in any row or column is 175, the magic constant for a 7×7
	board, since the numbers 1 through 49 sum to 1225, and 1225 ÷ 7 = 175.
</p>
