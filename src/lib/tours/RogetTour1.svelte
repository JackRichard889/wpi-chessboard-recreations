<h2 class="mb-3 text-xl font-bold">Roget's Knight Tour 1</h2>
<p class="mb-1">
	Peter Mark Roget (1779–1869) is best remembered for compiling Roget's Thesaurus (1852), but he was
	also a physician and an amateur mathematician with an interest in recreational puzzles. He devised
	a systematic method for constructing knight's tours by dividing the chessboard into four 4×4
	quadrants, building a tour within each, and then linking them together.
</p>
<p class="mb-1">
	This is a closed (re-entrant) tour: the knight can jump back from the final square to its
	starting point, forming an unbroken cycle across all 64 squares of the chessboard.
</p>
